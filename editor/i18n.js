const ru = Object.fromEntries(Object.entries(en).map(([source, translated]) => [translated, source]));

export function locale(language = globalThis.document?.documentElement?.lang || 'en') {
  return language.toLowerCase().split('-')[0] === 'ru' ? 'ru' : 'en';
}

export function t(key, values = {}, language) {
  const text = locale(language) === 'ru' ? ru[key] || key : en[key] || key;
  return text.replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
}
